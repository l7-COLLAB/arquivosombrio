import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {handleEditorialCandidates} from "../supabase/functions/editorial-candidates/handler.mjs";
const cfg=readFileSync(new URL("../supabase/config.toml",import.meta.url),"utf8");
const view=readFileSync(new URL("../admin-v2/js/editorial-candidates-view.js",import.meta.url),"utf8");
assert.match(cfg,/\[functions\.editorial-candidates\]\s*verify_jwt\s*=\s*true/);
assert.match(view,/functions\.invoke\("editorial-candidates",\{method:"GET"\}\)/);
assert.match(view,/obterSessaoAdminIsolada\(\)/);
const allowed="https://arquivosombrio.net.br";
const req=(method,headers)=>new Request("https://example.org",{method,headers});
let verifyCalls=0;
const verify=async(token)=>{verifyCalls++;return token==="admin"?{id:"1",app_metadata:{role:"admin"}}:null};
const pre=await handleEditorialCandidates(req("OPTIONS",{origin:allowed,"access-control-request-method":"GET","access-control-request-headers":"authorization,apikey,x-client-info"}),verify,[]);
assert.equal(pre.status,204);assert.equal(verifyCalls,0);
assert.equal(pre.headers.get("access-control-allow-origin"),allowed);
for(const h of ["authorization","apikey","x-client-info"])assert.match(pre.headers.get("access-control-allow-headers"),new RegExp(h));
const user=await handleEditorialCandidates(req("GET",{origin:allowed,authorization:"Bearer admin"}),verify,[]);
assert.equal(user.status,200);assert.equal(verifyCalls,1);
const forbidden=await handleEditorialCandidates(req("GET",{origin:"https://other.example",authorization:"Bearer admin"}),verify,[]);
assert.equal(forbidden.headers.get("access-control-allow-origin"),null);
console.log("Fase 5.65: compatibilidade simulada de CORS, JWT e invocacao Admin V2 verificada.");
