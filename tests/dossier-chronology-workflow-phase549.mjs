import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createEditorialReview,recordEditorialReview} from "../admin-v2/js/editorial-review-workflow.js";
const registry=JSON.parse(readFileSync(new URL("../docs/registro-decisoes-editoriais-fase5-47.json",import.meta.url),"utf8"));
const initial=createEditorialReview(registry.formularios);
assert.equal(initial.decisoes.length,2);
assert.equal(initial.publicacao_autorizada,false);
const review={id_caso:6,indice:11,decisao:"aprovar",responsavel:"Pessoa de teste",data_decisao:"2026-10-24",justificativa:"Simulacao, sem aprovacao real"};
assert.throws(()=>recordEditorialReview(initial,{...review,responsavel:""}));
assert.throws(()=>recordEditorialReview(initial,{...review,id_caso:999}));
const updated=recordEditorialReview(initial,review);
assert.equal(initial.decisoes[0].decisao,"pendente");
assert.equal(updated.decisoes[0].decisao,"aprovar");
assert.equal(updated.decisoes[0].historico.length,1);
assert.equal(updated.decisoes[1].decisao,"pendente");
assert.equal(updated.publicacao_autorizada,false);
assert.throws(()=>recordEditorialReview(updated,review));
assert.throws(()=>createEditorialReview([...registry.formularios,registry.formularios[0]]));
console.log("Fluxo simulado validado: sem publicacao.");
